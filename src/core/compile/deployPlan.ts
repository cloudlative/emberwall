// Guarded push: one script that backs up, checks, arms a rollback timer on the target itself,
// and applies. Emberwall then has to reconnect and confirm; if it cannot, the target rolls back.
// Every command here is fixed text; the only inputs are a numeric id, a timeout and a tool name.
import type { CompileResult } from './types';
import { fileText } from './types';

export interface DeployPlan {
  /** Files to upload, by fixed name. */
  files: { name: string; text: string }[];
  /** Generated build files that this push does not install (to be handled by hand). */
  manual: string[];
  script: string;
  /** Where the script itself is uploaded. */
  scriptPath: string;
  timeoutSeconds: number;
  confirmCommand: string;
  statusCommand: string;
  dir: string;
  state: string;
  /** Set when this build cannot be pushed automatically. */
  blocked?: string;
}

const MAIN: Record<string, string[]> = {
  nftables: ['emberwall.nft'],
  iptables: ['rules.v4', 'rules.v6'],
  ufw: ['emberwall-ufw.sh'],
  firewalld: ['emberwall-firewalld.sh'],
};

export interface DeployOptions {
  id: number;
  timeoutSeconds: number;
  /** Overridable for tests; production uses the defaults. */
  etcDir?: string;
  stateDir?: string;
  /** Tests only: allow a shorter rollback timer than the 15 second floor. */
  minTimeout?: number;
}

export function deployPlan(result: CompileResult, opts: DeployOptions): DeployPlan {
  const id = Math.trunc(opts.id);
  const timeout = Math.min(600, Math.max(opts.minTimeout ?? 15, Math.trunc(opts.timeoutSeconds)));
  if (!Number.isSafeInteger(id) || id < 0) throw new Error('invalid deployment id');
  const etc = opts.etcDir ?? '/etc/emberwall';
  const stateBase = opts.stateDir ?? '/var/lib/emberwall';
  // Paths are used unquoted in commands, so they may only contain plain path characters.
  if (![etc, stateBase].every((x) => /^\/[A-Za-z0-9_./-]+$/.test(x))) throw new Error('invalid deployment directory');
  const D = `${etc}/deploy-${id}`;
  const S = `${stateBase}/deploy-${id}`;
  const tool = result.target.tool;
  const names = MAIN[tool];
  const files = result.files.filter((f) => names.includes(f.name)).map((f) => ({ name: f.name, text: fileText(f) }));
  const manual = result.files.filter((f) => !names.includes(f.name) && f.name !== 'emberwall-apply.sh').map((f) => f.name);

  let blocked: string | undefined;
  if (result.diagnostics.some((d) => d.level === 'error')) blocked = 'The build has errors. Fix them before pushing.';
  else if (files.length !== names.length) blocked = 'The build is missing its main ruleset file.';
  else if ((tool === 'iptables' || tool === 'ufw') && files.some((f) => /-m set --match-set/.test(f.text))) {
    blocked = 'Blocklists on this tool need ipset sets created first; push this build by hand with the generated files.';
  }

  const steps: Record<string, { backup: string[]; check: string[]; apply: string[]; rollback: string[] }> = {
    nftables: {
      backup: [`nft list ruleset > "$S/backup.nft"`],
      check: [`nft -c -f "$D/emberwall.nft"`],
      apply: [`nft -f "$D/emberwall.nft"`],
      rollback: ['nft flush ruleset', `nft -f "$S/backup.nft"`],
    },
    iptables: {
      backup: [`iptables-save > "$S/backup.v4"`, `ip6tables-save > "$S/backup.v6"`],
      check: [`iptables-restore --test < "$D/rules.v4"`, `ip6tables-restore --test < "$D/rules.v6"`],
      apply: [`iptables-restore < "$D/rules.v4"`, `ip6tables-restore < "$D/rules.v6"`],
      rollback: [`iptables-restore < "$S/backup.v4"`, `ip6tables-restore < "$S/backup.v6"`],
    },
    ufw: {
      backup: [`cp -a /etc/ufw "$S/ufw"`, `cp -a /etc/default/ufw "$S/default-ufw"`, `ufw status | head -n 1 > "$S/ufw-state"`],
      check: [],
      apply: [`sh "$D/emberwall-ufw.sh"`],
      rollback: [`rm -rf /etc/ufw`, `cp -a "$S/ufw" /etc/ufw`, `cp -a "$S/default-ufw" /etc/default/ufw`, `if grep -q inactive "$S/ufw-state"; then ufw --force disable; else ufw reload; fi`],
    },
    firewalld: {
      backup: [`cp -a /etc/firewalld "$S/firewalld"`, `firewall-cmd --get-default-zone > "$S/default-zone"`],
      check: ['firewall-cmd --state'],
      apply: [`sh "$D/emberwall-firewalld.sh"`],
      rollback: [`rm -rf /etc/firewalld`, `cp -a "$S/firewalld" /etc/firewalld`, 'firewall-cmd --reload', `firewall-cmd --set-default-zone="$(cat "$S/default-zone")"`],
    },
  };
  const st = steps[tool];
  const L: string[] = [];
  L.push('#!/bin/sh');
  L.push(`# Emberwall guarded push ${id} (${tool}). Generated by the Emberwall server; do not edit.`);
  L.push('set -u');
  L.push(`D='${D}'`);
  L.push(`S='${S}'`);
  L.push('umask 077');
  L.push('mkdir -p "$S" || { echo "cannot create state directory" >&2; exit 1; }');
  L.push('step() { echo "== $1"; }');
  L.push('fail() { echo "!! $1" >&2; exit 1; }');
  L.push('step "Backing up the running rules"');
  for (const c of st.backup) L.push(`${c} || fail "backup failed; nothing was changed"`);
  if (st.check.length > 0) {
    L.push('step "Checking the new rules"');
    for (const c of st.check) L.push(`${c} || fail "the new rules did not pass the check; nothing was changed"`);
  }
  L.push(`cat > "$S/rollback.sh" <<'EMBERWALL_ROLLBACK'`);
  L.push('#!/bin/sh');
  L.push(`S='${S}'`);
  L.push(`D='${D}'`);
  for (const c of st.rollback) L.push(c);
  L.push('touch "$S/rolledback"');
  L.push('EMBERWALL_ROLLBACK');
  // Keep or roll back is decided exactly once: the first to create $S/decided (mkdir is atomic)
  // wins, so a confirmation that arrives while the timer is rolling back reports "rolledback".
  L.push(`cat > "$S/confirm.sh" <<'EMBERWALL_CONFIRM'`);
  L.push(`if mkdir '${S}/decided' 2>/dev/null; then touch '${S}/confirmed' && echo confirmed; elif [ -e '${S}/confirmed' ]; then echo confirmed; else echo rolledback; fi`);
  L.push('EMBERWALL_CONFIRM');
  L.push(`cat > "$S/status.sh" <<'EMBERWALL_STATUS'`);
  L.push(`if [ -e '${S}/rolledback' ]; then echo rolledback; elif [ -e '${S}/confirmed' ]; then echo confirmed; elif [ -d '${S}/decided' ]; then echo rollingback; else echo pending; fi`);
  L.push('EMBERWALL_STATUS');
  L.push(`step "Arming automatic rollback in ${timeout} seconds"`);
  L.push(`( trap '' HUP; sleep ${timeout}; mkdir "$S/decided" 2>/dev/null && sh "$S/rollback.sh" > "$S/rollback.log" 2>&1 ) > /dev/null 2>&1 < /dev/null &`);
  L.push('step "Applying"');
  L.push('if ! (');
  L.push('  set -e');
  for (const c of st.apply) L.push(`  ${c}`);
  L.push('); then');
  L.push('  echo "!! apply failed; rolling back now" >&2');
  L.push('  mkdir "$S/decided" 2>/dev/null');
  L.push('  sh "$S/rollback.sh" > "$S/rollback.log" 2>&1');
  L.push('  exit 1');
  L.push('fi');
  L.push('step "Applied. Waiting for confirmation"');

  return {
    files,
    manual,
    script: L.join('\n') + '\n',
    confirmCommand: `sh ${S}/confirm.sh`,
    statusCommand: `sh ${S}/status.sh`,
    scriptPath: `${D}/deploy.sh`,
    timeoutSeconds: timeout,
    dir: D,
    state: S,
    blocked,
  };
}
