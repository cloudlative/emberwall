import type { Target } from '../targets';

export interface OutLine {
  text: string;
  /** Rule (or NAT rule) that produced this line, for click-through in the UI. */
  ruleId?: string;
}

export type OutLang = 'iptables' | 'nft' | 'shell' | 'xml';

export interface OutFile {
  name: string;
  /** Where the file normally lives on the target system (informational). */
  path: string;
  lang: OutLang;
  description: string;
  lines: OutLine[];
}

export interface Diagnostic {
  level: 'info' | 'warn' | 'error';
  /** fallback: emitted differently for this version; unsupported: could not be expressed at all. */
  kind: 'fallback' | 'unsupported' | 'note' | 'invalid';
  message: string;
  ruleId?: string;
}

export interface CompileResult {
  target: Target;
  files: OutFile[];
  diagnostics: Diagnostic[];
}

export class Out {
  lines: OutLine[] = [];
  push(text: string, ruleId?: string): this {
    this.lines.push(ruleId ? { text, ruleId } : { text });
    return this;
  }
  blank(): this {
    if (this.lines.length > 0 && this.lines[this.lines.length - 1].text !== '') this.lines.push({ text: '' });
    return this;
  }
  add(lines: OutLine[]): this {
    this.lines.push(...lines);
    return this;
  }
}

export class Diags {
  list: Diagnostic[] = [];
  private seen = new Set<string>();
  private put(d: Diagnostic) {
    const key = `${d.level}|${d.ruleId ?? ''}|${d.message}`;
    if (this.seen.has(key)) return;
    this.seen.add(key);
    this.list.push(d);
  }
  note(message: string, ruleId?: string) {
    this.put({ level: 'info', kind: 'note', message, ruleId });
  }
  fallback(message: string, ruleId?: string) {
    this.put({ level: 'warn', kind: 'fallback', message, ruleId });
  }
  unsupported(message: string, ruleId?: string) {
    this.put({ level: 'warn', kind: 'unsupported', message, ruleId });
  }
  invalid(message: string, ruleId?: string) {
    this.put({ level: 'error', kind: 'invalid', message, ruleId });
  }
}

export function fileText(f: OutFile): string {
  return f.lines.map((l) => l.text).join('\n') + '\n';
}

export const BANNER = 'Generated by Emberwall';

export function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}
